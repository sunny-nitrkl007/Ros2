#####################################################
## makeInterfaceTypes (none)
#####################################################
sub makeInterfaceTypes
{
  printf("Generating InterfaceTypes.h\n");
  open( INTERFACEFILE, ">>$interfaceDir/InterfaceTypes.h" );
  print INTERFACEFILE "#ifndef _" . $clDataType . "InterfaceTypes_h_\n";
  print INTERFACEFILE "#define _" . $clDataType . "InterfaceTypes_h_\n\n";
  print INTERFACEFILE "#include <ais/interfaces/baseTypes/InputInterface.h>\n";
  print INTERFACEFILE "#include <ais/interfaces/baseTypes/OutputInterface.h>\n";
  print INTERFACEFILE "#include \"" . $clDataType . ".h\"\n\n";
  print INTERFACEFILE "typedef interfaces::baseTypes::InputInterface<" . $clDataType . "> " . $clDataType . "Input;\n";

  print INTERFACEFILE "typedef interfaces::baseTypes::OutputInterface<"
    . $clDataType . "> "
    . $clDataType
    . "Output;\n";
    

  print INTERFACEFILE "\n";
  print INTERFACEFILE "namespace interfaces\n";
  print INTERFACEFILE "{\n";
  print INTERFACEFILE "  template<>\n";
  print INTERFACEFILE "  inline std::string getDefaultInterfaceName<". $clDataType . "Input>()\n";
  print INTERFACEFILE "  {\n";
  print INTERFACEFILE "    return \"". $clDataType . "Input\";\n";
  print INTERFACEFILE "  }\n";
  print INTERFACEFILE "\n";
  print INTERFACEFILE "  template<>\n";
  print INTERFACEFILE "  inline std::string getDefaultInterfaceName<". $clDataType . "Output>()\n";
  print INTERFACEFILE "  {\n";
  print INTERFACEFILE "    return \"". $clDataType . "Output\";\n";
  print INTERFACEFILE "  }\n";
  print INTERFACEFILE "}\n";
  print INTERFACEFILE "\n";

  print INTERFACEFILE "#endif\n";
  close INTERFACEFILE;
}

#####################################################
## Add interface to $interfaceDir/SConscript
#####################################################
sub updateInterfacesSConscript
{
  open my $fh, $interfacesSConscript or die "Could not open $interfacesSConscript: $!";
  my @lines = grep /$clInterfaceName/, <$fh>;
  close $fh;

  if ( scalar(@lines) == 0 )
  {
    print "Updating $interfacesSConscript\n";
    open my $fh, ">>$interfacesSConscript";
    print $fh "baseEnv.buildit(\'$clInterfaceName\', [\'suse\'])\n";
  }
}

