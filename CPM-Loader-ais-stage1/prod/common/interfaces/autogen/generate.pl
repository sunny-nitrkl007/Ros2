#####################################################
## makeRestorable (TargetDir)
#####################################################
sub makeSConscript
{
  my $target_dir       = shift;
  my @sourceFiles      = qw(SConscript);
  my $useCsvable       = "";
  my $useTextWritable  = "";
  my $useRestorable    = "";
  my $useTypeTraits    = "#";

  # Csvable
  if ( ( not defined $clCsvable ) && ( not defined $clGenerateAll ) )
  {
    $useCsvable = "#";
  }

  # TextWritable
  if ( ( not defined $clTextWritable ) && ( not defined $clGenerateAll ) )
  {
    $useTextWritable = "#";
  }

  # Restorable
  if ( ( not defined $clRestorable ) && ( not defined $clGenerateAll ) )
  {
    $useRestorable = "#";
  }

  # TypeTraits
  if ( defined $clCsvable || defined $clTextWritable || defined $clGenerateAll )
  {
    $useTypeTraits = "";
  }

  foreach my $filename (@sourceFiles)
  {
    system( "/usr/bin/awk "
        . "-v DataType=\"$clDataType\" "
        . "-v UseCsvable=\"$useCsvable\" "
        . "-v UseTextWritable=\"$useTextWritable\" "
        . "-v UseRestorable=\"$useRestorable\" "
        . "-v UseTypeTraits=\"$useTypeTraits\" "
        . "-v Year=\"$year\" "
        . "-f $interfacesDir/autogen/genInterface.awk $interfacesDir/autogen/templates/$filename > $target_dir/$filename\n"
    );
  }
}

