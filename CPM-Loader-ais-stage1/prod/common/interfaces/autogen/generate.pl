sub help
{
  print("Usage: \n"
      . "  --help|-h            print this help message\n" . "\n"
      . "  --interfaceName|-i   (required) top-level name of the interface, \n"
      . "                       this will also be the directory name directly under prod/common/interfaces\n"
      . "  --pathToDataType|-p  (optional) path to the data type as it should appear in an #include directive\n"
      . "                       (if omitted, the path is inferred from the -i option)\n"
      . "  --dataTypeName|-d    (optional) class name of the data type\n"
      . "                       (if omitted, the data type is inferred from the -i option)\n"
      . "  --csvable            (optional) generate csvable type trait (can be used on an existing interface)\n"
      . "  --textWritable       (optional) generate textWritable type trait (can be used on an existing interface)\n"
      . "  --restorable|-r      (optional) generate restorable (can be used on an existing interface)\n"
      . "  --all|-a             Same as -t -k -r -w\n"
      . "  --sconsscript|-s     only generate the scons script (will not overwrite other files)\n"
      . "  --fix|-f <name>      Attempts to construct a SConscript from the directory structure <name> = interface name\n"
      . "\nExamples: "
      . "\nTo generate the simplest interface with only Channels:\n"
      . "\t./generate.pl -i SomeNewInterface\n"
      . "\nTo generate an interface that uses everything (Channels, Restorable, TypeTraits):\n"
      . "\t./generate.pl -i SomeNewInterface -a\n"
      . "\nTo generate a SConscript for an existing interface, manually specifying a configuration (i.e. Channels, Restorable, TypeTraits):\n"
      . "\t./generate.pl -i SomeNewInterface -s -r \n"
      . "\nTo generate a SConscript for an existing interface, autodetecting the correct configuration:\n"
      . "\t./generate.pl -f <interface name>\n"
      . "\n" );
}

#####################################################
## makeChannel ("Input" or "Output", TargetDir)
######################################################
sub makeChannel
{
  my $io          = shift;
  my $target_dir  = shift;
  my @sourceFiles = qw( channel.cpp channel.h);

  system("/bin/mkdir -p $target_dir");

  foreach my $filename (@sourceFiles)
  {
    system( "/usr/bin/awk "
        . "-v DataType=\"$clDataType\" "
        . "-v InOut=\"$io\" "
        . "-v PathToDataType=\"$clPathToDataType\" "
        . "-v IntfName=\"$clInterfaceName\" "
        . "-v Year=\"$year\" "
        . "-f $interfacesDir/autogen/genInterface.awk $interfacesDir/autogen/templates/$filename > $target_dir/$filename\n"
    );
  }
}

